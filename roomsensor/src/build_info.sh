#!/bin/bash
# Stamps a build with its version and time. Runs on every build (main/CMakeLists.txt).
#
#   build_info.sh <project dir> <out .c> <out .json>
#
# The .c is compiled into the firmware (main/build_info.h), which compares the time with the OTA
# manifest's build_timestamp_epoch to decide whether to update. deploy_ota.sh writes the manifest
# from the .json, so the two always agree.
#
# Version: the short git hash for a clean tree, revYYYYMMDDHHMMSS-<hash>-dirty otherwise.
set -euo pipefail

project_dir=$1
out_c=$2
out_json=$3

cd "$project_dir"
git update-index --refresh >/dev/null 2>&1 || true
hash=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
describe=$(git describe --tags --always --dirty 2>/dev/null || echo unknown)

# One clock reading for every form of the time (BSD and GNU date agree on these formats)
read -r epoch iso compact <<<"$(date -u +'%s %Y-%m-%dT%H:%M:%SZ %Y%m%d%H%M%S')"

if [[ "$describe" == *-dirty ]]; then
    version="rev${compact}-${hash}-dirty"
else
    version="$hash"
fi

cat >"$out_c.tmp" <<EOF
// Generated by build_info.sh at build time; do not edit.
#include <stdint.h>
const char BUILD_INFO_VERSION[] = "${version}";
const int64_t BUILD_INFO_TIMESTAMP = ${epoch}LL;
EOF
mv "$out_c.tmp" "$out_c"

cat >"$out_json.tmp" <<EOF
{
  "version": "${version}",
  "git_describe": "${describe}",
  "build_timestamp": "${iso}",
  "build_timestamp_epoch": ${epoch}
}
EOF
mv "$out_json.tmp" "$out_json"

echo "Build ${version}, ${iso}"
